// Model profiles (D-05a, D-07): the delegate catalog defines a `calidad` and a
// `costo` profile; each runtime with native agent files gets one profile per
// project. The same renderers produce the checked-in adapters (default
// profile) and the files installed into a target repository (chosen profile).
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const generatedMarker = 'Generated by scripts/sync-delegate-runtime-adapters.mjs. Do not edit.';
export const installedCatalogPath = 'templates/repo-overlay-fhh-ia-ecosystem-full/.agents/model-routing/delegate-agent-catalog.json';
export const modelProfileNames = Object.freeze(['calidad', 'costo']);
export const profiledRuntimes = Object.freeze(['claude', 'codex', 'copilot']);

export const installedDelegateContractPath = 'templates/repo-overlay-fhh-ia-ecosystem-full/.agents/delegation/delegate-contract.md';
const summaryStart = '<!-- delegate-contract:summary:start -->';
const summaryEnd = '<!-- delegate-contract:summary:end -->';

// The adapters embed the summary block of the delegate contract verbatim.
export function extractDelegateContractSummary(contract) {
  const start = contract.indexOf(summaryStart);
  const end = contract.indexOf(summaryEnd);
  if (start < 0 || end < start) throw new Error('delegate-contract.md must contain the summary markers in order.');
  return contract.slice(start + summaryStart.length, end).trim();
}

export async function loadDelegateContractSummary({ root = packageRoot, relativePath = installedDelegateContractPath } = {}) {
  return extractDelegateContractSummary(await fs.readFile(path.join(root, relativePath), 'utf8'));
}

export async function loadDelegateCatalog({ root = packageRoot, relativePath = installedCatalogPath, contractPath = installedDelegateContractPath } = {}) {
  const catalog = JSON.parse(await fs.readFile(path.join(root, relativePath), 'utf8'));
  catalog.delegateContractSummary = await loadDelegateContractSummary({ root, relativePath: contractPath });
  return catalog;
}

export function defaultProfileFor(catalog, runtime) {
  return catalog.modelProfiles.defaultByRuntime[runtime] ?? 'costo';
}

export function parseProfileOption(value) {
  const profiles = {};
  if (value === undefined || value === null || String(value).trim() === '') return profiles;
  for (const token of String(value).split(',').map((item) => item.trim()).filter(Boolean)) {
    const [runtime, profile] = token.split('=').map((item) => item?.trim());
    if (!profiledRuntimes.includes(runtime)) {
      throw new Error(`Unsupported --profile runtime "${runtime}". Use one of: ${profiledRuntimes.join(', ')}.`);
    }
    if (!modelProfileNames.includes(profile)) {
      throw new Error(`Unsupported --profile value "${profile}" for ${runtime}. Use calidad or costo.`);
    }
    profiles[runtime] = profile;
  }
  return profiles;
}

// Explicit option wins, then the value stored in install-state, then the
// catalog default for the runtime. Only selected runtimes with agent files get
// an entry.
export function resolveModelProfiles({ catalog, runtimes = [], requested = {}, stored = {} }) {
  const resolved = {};
  for (const runtime of runtimes) {
    if (!profiledRuntimes.includes(runtime)) continue;
    resolved[runtime] = requested[runtime] ?? stored?.[runtime] ?? defaultProfileFor(catalog, runtime);
  }
  return resolved;
}

export function agentTierFor(catalog, profile, slug) {
  const tier = catalog.modelProfiles.profiles[profile]?.agentTiers?.[slug];
  if (!tier) throw new Error(`No ${profile} tier defined for delegate ${slug}.`);
  return tier;
}

export function renderCapabilities(capabilities) {
  return `Model routing capabilities: catalog discovery=${capabilities.discoverCatalog}, subagent model pinning=${capabilities.pinSubagentModel}, subagent tier pinning=${capabilities.pinSubagentTier}, automatic fallback=${capabilities.autoFallback}.`;
}

function renderProfileLine(profile, tier) {
  return `Model profile: ${profile} · tier: ${tier}. Change it with \`workflow-kit update --profile <runtime>=<calidad|costo>\`; do not edit this file. Critical concerns may still escalate the tier per \`.agents/model-routing/README.md\`.`;
}

function bodyContract(agent, catalog) {
  if (!catalog.delegateContractSummary) throw new Error('Delegate catalog is missing the delegate contract summary.');
  return `The parent must provide the assigned scope, ownership, acceptance criteria, validation, and handoff requirements. ${agent.writable ? 'Edit only explicitly owned files.' : 'Do not edit files.'} Do not redefine the shared workflow or act outside the assigned slice.

${catalog.delegateContractSummary}`;
}

export function renderCodexAgent(agent, catalog, profile = defaultProfileFor(catalog, 'codex')) {
  const sandboxMode = agent.writable ? 'workspace-write' : 'read-only';
  const tier = agentTierFor(catalog, profile, agent.slug);
  const settings = catalog.modelProfiles.runtimeTierSettings.codex[tier];
  const modelLine = settings.model ? `model = "${settings.model}"\n` : '';
  return `# ${generatedMarker}
name = "${agent.slug}"
description = "${agent.description}"
sandbox_mode = "${sandboxMode}"
${modelLine}model_reasoning_effort = "${settings.model_reasoning_effort}"
developer_instructions = """
You are ${agent.alias}. Before acting, read and follow ${agent.shared_skill_path} and .agents/delegation/delegate-contract.md.

${bodyContract(agent, catalog)}

${renderCapabilities(catalog.runtimeCapabilities.codex)}
${renderProfileLine(profile, tier)}
"""
`;
}

export function renderCopilotAgent(agent, catalog, profile = defaultProfileFor(catalog, 'copilot')) {
  const tools = agent.writable ? '["read", "search", "edit", "execute"]' : '["read", "search", "execute"]';
  const tier = agentTierFor(catalog, profile, agent.slug);
  const candidates = catalog.copilotModelRouting.tiers[tier];
  return `---
name: ${agent.alias}
description: ${agent.description}
tools: ${tools}
model: ${JSON.stringify(candidates)}
user-invocable: true
---

<!-- ${generatedMarker} -->

Before acting, read and follow \`${agent.shared_skill_path}\` and \`.agents/delegation/delegate-contract.md\`.

${bodyContract(agent, catalog)}

${renderCapabilities(catalog.runtimeCapabilities.copilot)}
${renderProfileLine(profile, tier)}

Copilot invocation identity: this agent's registered Copilot name is \`${agent.alias}\`. The Claude slug \`${agent.slug}\` belongs to a different runtime and is not the Copilot agent name.

Model routing: tier=${tier}; candidates=${candidates.join(' | ')}. The \`model\` front matter is a static priority list limited to this tier; it does not prove which model executed and it must be validated against the options the runtime currently exposes.

The parent that starts this agent resolves the target tier from observed options and passes both \`agentName\` (\`${agent.alias}\`) and the selected qualified \`model\` explicitly to \`runSubagent\`, following the Copilot invocation protocol in \`.agents/skills/02-implement/implement-prd/reference/subagent-prompts.md\`. This agent cannot choose or change the model it is already running with, and these capabilities do not imply that a model was selected or switched for this run.
`;
}


// Kit text fixes found by a pilot that installed the kit in a fresh project.
// The text of the kit must be true in an installed project (no scripts/ folder,
// no package.json scripts of the kit repository) and must be identical in the
// repository copy (.agents) and in the overlay template that init installs.
// The checks are structural so a regression class is caught, not one string.

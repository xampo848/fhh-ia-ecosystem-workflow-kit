const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bin = path.join(root, 'bin', 'workflow-kit.mjs');
const overlay = 'templates/repo-overlay-fhh-ia-ecosystem-full';
// The two copies of the kit tree.
const kitRoots = ['.agents', `${overlay}/.agents`];
// Every markdown file a user's agent can read after init: the kit tree, the
// generated adapters, and the docs the overlay installs.
const adapterFiles = [
  'CLAUDE.md', 'AGENTS.md', 'ANTIGRAVITY.md', '.github/copilot-instructions.md',
  'templates/runtime-adapters/claude/CLAUDE.md', 'templates/runtime-adapters/agents-md/AGENTS.md',
  'templates/runtime-adapters/antigravity/ANTIGRAVITY.md',
  'templates/runtime-adapters/copilot/.github/copilot-instructions.md'
];

async function walk(directory) {
  const out = [];
  for (const entry of await fs.readdir(path.join(root, directory), { withFileTypes: true })) {
    const relative = `${directory}/${entry.name}`;
    if (entry.isDirectory()) out.push(...await walk(relative));
    else out.push(relative);
  }
  return out;
}

const read = (relative) => fs.readFile(path.join(root, relative), 'utf8');
const markdown = (files) => files.filter((file) => file.endsWith('.md'));

async function kitMarkdown() {
  const files = [];
  for (const kitRoot of kitRoots) files.push(...markdown(await walk(kitRoot)));
  files.push(...markdown(await walk(`${overlay}/docs`)));
  return files;
}

async function kitText() {
  return [...await kitMarkdown(), ...adapterFiles];
}

const forEachCopy = async (relativeToKit, check) => {
  for (const kitRoot of kitRoots) check(await read(`${kitRoot}/${relativeToKit}`), `${kitRoot}/${relativeToKit}`);
};

// Files that name the kit repository's own tooling on purpose. The router evals
// are not here: they are "maintainers only" but still installed, so they may not
// send a project to a command that does not exist there.
const maintainerOnly = [
  /\/skills\/04-crosscutting\/impeccable\//, // vendored third-party skill with its own CLI
  /\/skills\/05-caveman\/caveman-compress\//
];

test('fix 1: no kit text sends an installed project to scripts/, npm run, bun run or check:* of the kit repository', async () => {
  const repoOnly = /\bnode scripts\/|\bnpm run\b|\bbun run\b|\bcheck:(workflow|templates|release|docs|legal|security)\b|scripts\/(delegate-agent-catalog|sync-|validate-|build-plugin)/;
  const offenders = [];
  for (const file of await kitText()) {
    if (maintainerOnly.some((pattern) => pattern.test(file))) continue;
    (await read(file)).split('\n').forEach((line, index) => {
      if (/Generated by scripts\//.test(line)) return; // provenance marker of a generated file
      if (repoOnly.test(line)) offenders.push(`${file}:${index + 1}: ${line.trim().slice(0, 100)}`);
    });
  }
  assert.deepEqual(offenders, []);
});


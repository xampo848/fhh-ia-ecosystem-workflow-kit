test('fix 5 guard: a 0.18.1 adapter still gets the split decision, so the generated block must keep matching what 0.18.1 wrote', async () => {
  // split is offered only when the adapter holds the current kit text byte for
  // byte. Editing the generated pre-filter block (even one word) makes every
  // upgrade from a 0.18.1 install lose split. If this fails, do not edit the
  // fixture or this test: restore the block, or ship a migration for it.
  const adapters = ['CLAUDE.md', 'AGENTS.md', 'ANTIGRAVITY.md', '.github/copilot-instructions.md'];
  const target = await makeTempRepo();
  await installLegacy0181(target, { runtimes: ['claude', 'codex', 'copilot', 'antigravity'] });
  for (const adapter of adapters) await fs.appendFile(path.join(target, adapter), '\nLocal edit.\n');
  const plan = await buildUpdatePlan({ targetPath: target });
  const migration = plan.migrations.find((item) => item.id === '0.22.0-kit-overlay-layout');
  for (const adapter of adapters) {
    const pending = migration.pending.find((item) => item.relativePath === adapter);
    assert.ok(pending, `${adapter} is pending`);
    assert.deepEqual(pending.decisions, ['keep', 'discard', 'split'], `${adapter} must still offer split`);
  }
});

// Balanced fences by the CommonMark rule: a closing fence uses the same
// character, is at least as long as the opening one, and has no info string.
function unbalancedFence(text) {
  let open = null;
  for (const [index, line] of text.split('\n').entries()) {
    const match = /^\s*(`{3,}|~{3,})(.*)$/.exec(line);
    if (!match) continue;
    if (open === null) open = { char: match[1][0], length: match[1].length, line: index + 1 };
    else if (match[1][0] === open.char && match[1].length >= open.length && match[2].trim() === '') open = null;
  }
  return open;
}

test('fix 7: code fences are balanced in every kit markdown file, and the quality bar has none left over', async () => {
  const offenders = [];
  for (const file of await kitMarkdown()) {
    const open = unbalancedFence(await read(file));
    if (open) offenders.push(`${file}:${open.line}`);
  }
  assert.deepEqual(offenders, []);
  await forEachCopy('skills/01-product/create-prd/reference/quality-bar.md', (text, file) => assert.ok(!text.includes('```'), file));
});


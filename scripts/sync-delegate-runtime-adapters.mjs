#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedMarker = 'Generated by scripts/sync-delegate-runtime-adapters.mjs. Do not edit.';

export async function validateDelegateRuntimeAdapters({ root = packageRoot } = {}) {
  const expected = await expectedDelegateRuntimeAdapters({ root });
  const failures = [];

  for (const [relativePath, content] of expected) {
    try {
      const actual = await fs.readFile(path.join(root, relativePath), 'utf8');
      if (actual !== content) failures.push(`Generated delegate adapter drift: ${relativePath}`);
    } catch {
      failures.push(`Generated delegate adapter missing: ${relativePath}`);
    }
  }

  return { ok: failures.length === 0, failures, expected };
}

export async function writeDelegateRuntimeAdapters({ root = packageRoot } = {}) {
  const expected = await expectedDelegateRuntimeAdapters({ root });
  for (const [relativePath, content] of expected) {
    const targetPath = path.join(root, relativePath);
    await fs.mkdir(path.dirname(targetPath), { recursive: true });
    await fs.writeFile(targetPath, content, 'utf8');
  }
  return expected.size;
}

async function expectedDelegateRuntimeAdapters({ root }) {
  const catalog = JSON.parse(await fs.readFile(path.join(root, 'scripts/delegate-agent-catalog.json'), 'utf8'));
  const outputs = new Map();
  const matrix = renderMatrix(catalog.agents, catalog.runtimeCapabilities);

  outputs.set('.agents/skills/02-implement/implement-prd/reference/delegate-skill-matrix.md', matrix);
  outputs.set('templates/repo-overlay-fhh-ia-ecosystem-full/.agents/skills/02-implement/implement-prd/reference/delegate-skill-matrix.md', matrix);

  for (const agent of catalog.agents) {
    for (const [relativePath, content] of runtimeAdapterFiles(agent, catalog.runtimeCapabilities)) {
      outputs.set(relativePath, content);
      outputs.set(path.join('templates/runtime-adapters', runtimeForPath(relativePath), relativePath), content);
    }
  }

  return outputs;
}

function runtimeAdapterFiles(agent, runtimeCapabilities) {
  return [
    [`.codex/agents/${agent.slug}.toml`, renderCodexAgent(agent, runtimeCapabilities.codex)],
    [`.github/agents/${agent.slug}.agent.md`, renderCopilotAgent(agent, runtimeCapabilities.copilot)],
    [`.claude/agents/${agent.slug}.md`, renderClaudeAgent(agent, runtimeCapabilities.claude)]
  ];
}

function runtimeForPath(relativePath) {
  if (relativePath.startsWith('.codex/')) return 'codex';
  if (relativePath.startsWith('.github/')) return 'copilot';
  if (relativePath.startsWith('.claude/')) return 'claude';
  throw new Error(`Unsupported runtime adapter path: ${relativePath}`);
}

function renderMatrix(agents, runtimeCapabilities) {
  const primary = agents.filter((agent) => agent.section === 'Delegate Skill Matrix');
  const helpers = agents.filter((agent) => agent.section === 'Cavecrew Helper Delegates');
  const renderRow = (agent) => [
    agent.step,
    `\`${agent.skill}\``,
    agent.alias,
    `\`${agent.shared_skill_path}\``,
    `\`.codex/agents/${agent.slug}.toml\``,
    `\`.github/agents/${agent.slug}.agent.md\``,
    `\`.claude/agents/${agent.slug}.md\``,
    'Inline: no declared custom-agent file format',
    agent.writes
  ].map((cell) => `| ${cell} `).join('') + '|';

  return `# Delegate Skill Matrix

<!-- ${generatedMarker} -->

Use the shared skill path as the execution contract. Native adapters are generated from the same catalog and only specialize runtime discovery and tool configuration.

Antigravity 2.0 documents project-scoped agents, worktrees, reusable skills, MCPs, and hooks, but does not declare a project custom-agent file format. Run the shared skill inline there until Google publishes one; do not create an undocumented adapter directory.

## Delegate Skill Matrix

| Step | Skill | Alias | Shared skill path | Codex adapter | Copilot adapter | Claude adapter | Antigravity 2.0 | Writes |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${primary.map(renderRow).join('\n')}

## Cavecrew Helper Delegates

Use these as secondary helpers from the main implement-prd delegates when the narrower contract is enough:

| Helper | Skill | Shared skill path | Codex adapter | Copilot adapter | Claude adapter | Antigravity 2.0 | Typical use |
| --- | --- | --- | --- | --- | --- | --- | --- |
${helpers.map((agent) => `| ${agent.alias} | \`${agent.skill}\` | \`${agent.shared_skill_path}\` | \`.codex/agents/${agent.slug}.toml\` | \`.github/agents/${agent.slug}.agent.md\` | \`.claude/agents/${agent.slug}.md\` | Inline: no declared custom-agent file format | ${agent.typical_use} |`).join('\n')}

The primary owner skill remains accountable for the slice. Cavecrew helpers do not change ownership; they only compress a narrower subtask.

## Parallelization Rules

Good candidates for parallel work:

- Read-only readiness and discovery follow-up questions on different domains.
- Backend and frontend implementation only when API contracts are already fixed and file ownership is disjoint.
- Final QA review while the orchestrator prepares the delivery summary, if no more edits are expected.

Do not parallelize:

- Two writers on the same file.
- Frontend consuming an API shape that backend has not decided.
- Validation fixes that may alter implementation files another slice still owns.
- Destructive migrations or tenancy-sensitive work.

## Ownership Contract

Every writable delegate receives:

- Files owned.
- Files forbidden.
- Acceptance criteria.
- Validation expected.
- Handoff output format.

If ownership is unclear, stop and ask before editing.

## Delegation Efficiency Gate

Before launching any delegate, name the benefit in one short phrase:

- \`risk\`: independent review prevents a likely defect;
- \`context\`: delegate can solve with narrower context than the orchestrator;
- \`ownership\`: one writer owns a bounded file set;
- \`validation\`: delegate can run or stabilize focused checks;
- \`bias\`: fresh context review is materially useful.

If none apply, do the work inline in the orchestrator and record why delegation was skipped.

## Runtime Model Routing Capabilities

These are declarative capabilities of the generated runtime adapters. They do not imply that a model was selected or switched for a specific run.

| Runtime | Discover catalog | Pin subagent model | Pin subagent tier | Auto fallback |
| --- | --- | --- | --- | --- |
${Object.entries(runtimeCapabilities).map(([runtime, capabilities]) => `| ${runtime} | ${capabilities.discoverCatalog} | ${capabilities.pinSubagentModel} | ${capabilities.pinSubagentTier} | ${capabilities.autoFallback} |`).join('\n')}
`;
}

function renderCodexAgent(agent, capabilities) {
  const sandboxMode = agent.writable ? 'workspace-write' : 'read-only';
  return `# ${generatedMarker}
name = "${agent.slug}"
description = "${agent.description}"
sandbox_mode = "${sandboxMode}"
developer_instructions = """
You are ${agent.alias}. Before acting, read and follow ${agent.shared_skill_path} and the applicable repository instructions.

The parent must provide the assigned scope, ownership, acceptance criteria, validation, and handoff requirements. ${agent.writable ? 'Edit only explicitly owned files.' : 'Do not edit files.'} Do not redefine the shared workflow or act outside the assigned slice.

${renderCapabilities(capabilities)}
"""
`;
}

function renderCopilotAgent(agent, capabilities) {
  const tools = agent.writable ? '["read", "search", "edit", "execute"]' : '["read", "search", "execute"]';
  return `---
name: ${agent.alias}
description: ${agent.description}
tools: ${tools}
user-invocable: true
---

<!-- ${generatedMarker} -->

Before acting, read and follow \`${agent.shared_skill_path}\` and the applicable repository instructions.

The parent must provide the assigned scope, ownership, acceptance criteria, validation, and handoff requirements. ${agent.writable ? 'Edit only explicitly owned files.' : 'Do not edit files.'} Do not redefine the shared workflow or act outside the assigned slice.

${renderCapabilities(capabilities)} These capabilities do not imply that a model was selected or switched for this run.
`;
}

function renderClaudeAgent(agent, capabilities) {
  const tools = agent.writable ? 'Read, Edit, Write, Grep, Glob, Bash' : 'Read, Grep, Glob, Bash';
  return `---
name: ${agent.slug}
description: ${agent.description}
tools: ${tools}
model: inherit
---

<!-- ${generatedMarker} -->

You are ${agent.alias}. Before acting, read and follow \`${agent.shared_skill_path}\` and the applicable repository instructions.

The parent must provide the assigned scope, ownership, acceptance criteria, validation, and handoff requirements. ${agent.writable ? 'Edit only explicitly owned files.' : 'Do not edit files.'} Do not redefine the shared workflow or act outside the assigned slice.

${renderCapabilities(capabilities)}
`;
}

function renderCapabilities(capabilities) {
  return `Model routing capabilities: catalog discovery=${capabilities.discoverCatalog}, subagent model pinning=${capabilities.pinSubagentModel}, subagent tier pinning=${capabilities.pinSubagentTier}, automatic fallback=${capabilities.autoFallback}.`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const shouldWrite = process.argv.includes('--write');
  const result = shouldWrite
    ? { ok: true, count: await writeDelegateRuntimeAdapters() }
    : await validateDelegateRuntimeAdapters();

  if (!result.ok) {
    console.error('Delegate runtime adapter validation failed:');
    for (const failure of result.failures) console.error(`- ${failure}`);
    process.exit(1);
  }

  console.log(shouldWrite
    ? `Wrote ${result.count} generated delegate runtime adapters.`
    : `Delegate runtime adapters are synchronized (${result.expected.size} files).`);
}
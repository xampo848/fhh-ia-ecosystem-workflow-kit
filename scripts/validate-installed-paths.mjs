#!/usr/bin/env node
// Guard against dangling path references in installed kit text.
//
// `workflow-kit init` writes kit text into a user's project. A path that text
// cites as something to read or run must exist there, or be declared as the
// project's own (optional, seeded, generated on demand), or be marked as a
// legacy fallback. This validator plans the install of each runtime set from
// the templates, scans the text files it would write, and fails on every
// reference that is none of those.
//
// Rule per reference (first match wins):
//   a  the install of that runtime set writes it (or a folder holding a file it writes)
//   b  the manifest says the project owns it: project_layout, a seed, or a generated entry
//   c  it is a glob or placeholder (<slug>, *, {..}, [..], YYYY) whose fixed folder prefix is valid by a or b
//   d  another runtime the kit supports installs it (a codex path in shared text)
//   e  it is the legacy path of a manifest legacy_paths pair and the same or an adjacent line says legacy, older installs, or fallback
//   f  it is in `allowlist` below (file, path prefix, reason)
// Two more categories keep the rule honest without listing each case:
//   - project documents: product docs the kit's skills write or read when the project has them
//     (the manifest's excluded_from_distribution plus `projectDocFolders`), exists-or-skip
//   - provenance: the "Generated by scripts/<name>" marker of a generated file names the kit
//     repository's generator, not something to run in the project
// JSON files are not scanned: they are generated catalogs and data (registry,
// manifest, settings) whose paths other validators already pin, not prose an
// agent follows.
// Usage: node scripts/validate-installed-paths.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { runtimeTemplatePaths } from '../src/runtime-matrix.mjs';
import { thirdPartyPrefixes } from './validate-skill-size.mjs';
import { isMainModule } from './is-main-module.mjs';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestFile = '.agents/workflow-kit/manifest.json';
const overlayTemplate = 'templates/repo-overlay-fhh-ia-ecosystem-full';
const osJunk = new Set(['.DS_Store', 'Thumbs.db', 'desktop.ini']);
const textExtensions = ['.md', '.toml'];
const legacyMarker = /legacy|older installs?|fallback/i;
const patternChars = /[<*{[]|YYYY/;
const roots = ['.agents', '.claude', '.github', '.codex', '.antigravity', 'docs', 'scripts', 'templates', 'src', 'test'];
const pathReference = new RegExp(`(?<![\\w./<>~$-])((?:${roots.map((root) => root.replace('.', '\\.')).join('|')})/[A-Za-z0-9._/<>*{}\\[\\]-]*|(?:CLAUDE|AGENTS|ANTIGRAVITY)\\.md)`, 'g');

// Product documents the project owns; the kit's skills write them there or read them when they exist.
export const projectDocFolders = [
  'docs/design/', 'docs/patterns/', 'docs/foundations/', 'docs/config/', 'docs/contracts/',
  'docs/workflow/handoffs/' // listed in the docs hub; the project creates it with its first handoff note
];
const provenanceMarker = /Generated by scripts\//;

// Runtime sets the guard checks by default: every one alone, all together, and none.
export const runtimeSets = [['neutral'], ['claude'], ['codex'], ['copilot'], ['antigravity'], ['claude', 'codex', 'copilot', 'antigravity']];

// The only exceptions, kept in one place: file (as installed), cited path, and why it is fine.
// A reference that is neither valid by the rule nor listed here fails the guard.
export const allowlist = [
  { file: '.agents/skills/06-patterns/authoring/init-legacy-attachments/SKILL.md', path: '.github/skills/', reason: 'native skill folder that project-owned attachments may live in; the skill migrates them, the kit never writes it' },
  { file: '.agents/skills/06-patterns/authoring/init-legacy-attachments/SKILL.md', path: '.codex/skills/', reason: 'same: native skill folder of Codex that the skill scans for legacy attachments' },
  { file: '.agents/skills/registry.md', path: '.github/skills/', reason: 'generated inventory names runtime wrapper folders that exist only as runtime compatibility symlinks' },
  { file: '.agents/skills/registry.md', path: '.codex/skills/', reason: 'same: Codex compatibility folder named by the generated inventory' },
  { file: '.agents/skills/01-product/create-prd/reference/traceability-tables.md', path: 'test/contrato/', reason: 'false positive: slash-separated list of validation kinds (test/contrato/smoke/evidencia), not a path' }
];

async function walk(root, relative = '') {
  const files = [];
  let entries;
  try {
    entries = await fs.readdir(path.join(root, relative), { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return files;
    throw error;
  }
  for (const entry of entries) {
    const child = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await walk(root, child));
    else if (entry.isFile() && !osJunk.has(entry.name)) files.push(child);
  }
  return files.sort();
}

// The files an install of `runtimes` writes, as target path -> source file (relative to root).
export async function plannedInstall(root, runtimes) {
  const sources = [overlayTemplate];
  for (const runtime of runtimes) {
    for (const templatePath of runtimeTemplatePaths[runtime] ?? []) sources.push(`templates/${templatePath}`);
  }
  const files = new Map();
  for (const source of sources) {
    for (const file of await walk(path.join(root, source))) {
      if (file !== 'README.md') files.set(file, `${source}/${file}`);
    }
  }
  return files;
}

function matchEntry(manifest, relativePath) {
  let best = null;
  for (const entry of manifest.paths) {
    const hit = entry.path.endsWith('/') ? relativePath.startsWith(entry.path) : relativePath === entry.path;
    if (hit && (!best || entry.path.length > best.path.length)) best = entry;
  }
  return best;
}

const dirOf = (reference) => (reference.endsWith('/') ? reference : `${reference}/`);

// Fixed folder prefix of a reference that contains a placeholder or glob.
function staticPrefix(reference) {
  const special = reference.search(patternChars);
  if (special < 0) return null;
  return reference.slice(0, reference.lastIndexOf('/', special) + 1);
}

export function extractReferences(content) {
  const lines = content.split('\n');
  const found = [];
  lines.forEach((text, index) => {
    for (const match of text.matchAll(pathReference)) {
      if (provenanceMarker.test(text)) continue;
      let reference = match[1].replace(/[.-]+$/, '');
      // A closing bracket the reference never opened belongs to the sentence ("[docs/x.md]").
      for (const [open, close] of [['[', ']'], ['{', '}'], ['<', '>']]) {
        while (reference.endsWith(close) && reference.split(close).length > reference.split(open).length) reference = reference.slice(0, -1);
      }
      if (reference.length > 1) found.push({ reference, line: index + 1 });
    }
  });
  return found;
}

function layoutCovers(manifest, reference) {
  const layout = manifest.project_layout ?? [];
  const asDir = dirOf(reference);
  return asDir === manifest.project_root || layout.some((item) => (item.endsWith('/') ? reference.startsWith(item) || asDir === item : reference === item));
}

// True when the manifest declares the path as the project's or as created on demand.
function declaredByManifest(manifest, reference) {
  if (layoutCovers(manifest, reference)) return true;
  const asDir = dirOf(reference);
  for (const entry of manifest.paths) {
    if (!(entry.class === 'seed' || entry.generated)) continue;
    if (entry.path.endsWith('/') ? reference.startsWith(entry.path) || asDir === entry.path : reference === entry.path) return true;
  }
  return false;
}

function isProjectDocument(manifest, reference) {
  const asDir = dirOf(reference);
  return [...(manifest.excluded_from_distribution ?? []), ...projectDocFolders].some((folder) => asDir.startsWith(folder));
}

function isWritten(files, reference) {
  if (files.has(reference)) return true;
  const asDir = dirOf(reference);
  for (const target of files.keys()) if (target.startsWith(asDir)) return true;
  return false;
}

// Reference -> verdict: null when valid, or a message that says what would make it valid.
function verdict({ reference, lines, line }, { manifest, files, everyRuntime }) {
  if (isWritten(files, reference) || declaredByManifest(manifest, reference) || isProjectDocument(manifest, reference)) return null;
  const prefix = staticPrefix(reference);
  if (prefix !== null && (isWritten(files, prefix) || declaredByManifest(manifest, prefix) || isProjectDocument(manifest, prefix) || isWritten(everyRuntime, prefix))) return null;
  if (prefix === null && isWritten(everyRuntime, reference)) return null;
  const legacy = manifest.legacy_paths ?? {};
  if (legacy[reference]) {
    const window = lines.slice(Math.max(0, line - 2), line + 1).join('\n');
    if (legacyMarker.test(window)) return null;
    return `is the legacy path of ${legacy[reference]}; say "legacy", "older installs", or "fallback" on the same or an adjacent line`;
  }
  if (prefix !== null) return `its fixed folder ${prefix} is not installed, declared by the manifest, or installed by another runtime`;
  return 'is not installed by this runtime set, declared project-owned or generated in the manifest, installed by another runtime, or allow-listed';
}

function isText(file) {
  return textExtensions.some((extension) => file.endsWith(extension));
}

// Scans the install of one runtime set. Returns the failures and how many references were scanned.
export async function validateInstalledTree(root, runtimes, { manifest, everyRuntime, allow = allowlist } = {}) {
  const files = await plannedInstall(root, runtimes);
  const failures = [];
  let scanned = 0;
  for (const [target, source] of files) {
    if (!isText(target) || thirdPartyPrefixes.some((prefix) => target.startsWith(prefix))) continue;
    const content = await fs.readFile(path.join(root, source), 'utf8');
    const lines = content.split('\n');
    for (const { reference, line } of extractReferences(content)) {
      scanned += 1;
      const problem = verdict({ reference, lines, line }, { manifest, files, everyRuntime });
      if (!problem) continue;
      if (allow.some((item) => item.file === target && reference.startsWith(item.path))) continue;
      failures.push(`${target}:${line}: ${reference} ${problem} (runtimes: ${runtimes.join('+')}).`);
    }
  }
  return { failures, scanned };
}

export async function validateInstalledPaths({ root = packageRoot, sets = runtimeSets, allow = allowlist } = {}) {
  let manifest;
  try {
    manifest = JSON.parse(await fs.readFile(path.join(root, manifestFile), 'utf8'));
  } catch (error) {
    return { ok: false, failures: [`${manifestFile}: cannot read the manifest (${error.message}).`], scanned: 0 };
  }
  const everyRuntime = await plannedInstall(root, Object.keys(runtimeTemplatePaths));
  const failures = [];
  let scanned = 0;
  for (const runtimes of sets) {
    const result = await validateInstalledTree(root, runtimes, { manifest, everyRuntime, allow });
    scanned += result.scanned;
    failures.push(...result.failures);
  }
  // The same defect shows in every runtime set that installs the file: report each reference once.
  const unique = [...new Set(failures.map((failure) => failure.replace(/ \(runtimes: [^)]*\)\.$/, '.')))];
  return { ok: unique.length === 0, failures: unique, scanned };
}

if (isMainModule(import.meta.url)) {
  const result = await validateInstalledPaths();
  if (!result.ok) {
    console.error('Installed kit text cites paths that no install provides:');
    for (const failure of result.failures) console.error(`- ${failure}`);
    process.exit(1);
  }
  console.log(`Installed kit text holds: ${result.scanned} path references across ${runtimeSets.length} runtime sets resolve in the install, the project overlay, or a marked legacy fallback.`);
}

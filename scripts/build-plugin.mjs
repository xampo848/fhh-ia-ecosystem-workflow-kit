#!/usr/bin/env node
// Makes the kit repository root the root of the plugin `fhh` (marketplace
// `fhh-ia-ecosystem`). The plugin uses the `.agents/**` tree in place, so the
// build copies nothing: it only generates the plugin manifests and the plugin
// skills (the explicit workflow wrappers plus `kit-root`, the one skill the
// model may load on its own to learn the kit root and the path rule).
// Usage: node scripts/build-plugin.mjs [--write]
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { claudeSkillDescription, claudeSkillEntries, listFiles } from './sync-claude-skills.mjs';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedMarker = 'Generated by scripts/build-plugin.mjs. Do not edit.';

export const pluginName = 'fhh';
export const marketplaceName = 'fhh-ia-ecosystem';
const agentPluginsSchema = 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json';
const pluginDescription = 'Workflow kit: routed workflow skills and delegates that run from the plugin while each repository keeps its own project overlay.';
const marketplaceDescription = 'Marketplace of the fhh workflow kit plugin.';

// Folders that hold only generated files: anything there that the build does
// not expect is an orphan. Later outputs (agents) add their folders here.
const generatedDirectories = ['.claude-plugin', 'skills'];

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderManifests(packageJson) {
  const repository = `https://github.com/${packageJson.workflowKit.repository}`;
  const identity = {
    name: pluginName,
    version: packageJson.version,
    description: pluginDescription,
    license: packageJson.license,
    repository
  };
  return new Map([
    ['plugin.json', json({ $schema: agentPluginsSchema, ...identity, keywords: packageJson.keywords })],
    ['.claude-plugin/plugin.json', json(identity)],
    ['.claude-plugin/marketplace.json', json({
      name: marketplaceName,
      owner: { name: marketplaceName },
      metadata: { description: marketplaceDescription, version: packageJson.version },
      plugins: [{ name: pluginName, source: './', description: pluginDescription }]
    })]
  ]);
}

const kitRootSentence = 'Kit root: `${CLAUDE_PLUGIN_ROOT}`. If that text shows an unexpanded variable, the kit root is the folder two levels above this file.';

function renderWrapper(entry) {
  return `---
name: ${entry.name}
description: "${claudeSkillDescription(entry)}"
disable-model-invocation: true
---

<!-- ${generatedMarker} -->

Explicit invocation of the \`${entry.name}\` workflow skill from the plugin \`${pluginName}\`.

${kitRootSentence}

Load \`<kit root>/${entry.path}\` ([${entry.path}](../../${entry.path})) and follow it. That file is the canonical procedure. Resolve every other path with the rule in the \`kit-root\` skill.

It is never invoked automatically: freeform requests keep going through the level pre-filter and \`workflow-router\`.
`;
}

function renderKitRoot() {
  return `---
name: kit-root
description: "Load before any N2/N3 work, and before reading a workflow kit path such as .agents/** or docs/workflow/**, in a repository whose adapter says the workflow kit runs as the plugin ${pluginName}. Gives the kit root and the rule that says which paths resolve under it."
---

<!-- ${generatedMarker} -->

The workflow kit runs as the plugin \`${pluginName}\`.

${kitRootSentence}

Path rule:

- Kit paths resolve under the kit root: \`.agents/**\` except \`.agents/project/**\` and \`.agents/workflow-kit/install-state.json\`; \`docs/workflow/**\`; and \`scripts/**\` when a kit file names it.
- Everything else resolves in the repository: \`.agents/project/**\`, \`.ai-work/**\`, \`docs/prd/**\`, and the project's own code and docs.
- Ignore \`.agents/project/\` under the kit root: the project overlay is the one in the repository.
- Never write under the kit root.

Delegates are named \`${pluginName}:<slug>\`, unless the project defines an agent with that slug: then the project agent wins. Every delegation brief carries the line \`Kit root: <absolute path>\`.

Next step: read \`<kit root>/.agents/instructions.md\`.
`;
}

export async function expectedPluginFiles({ root = packageRoot } = {}) {
  const packageJson = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
  const outputs = renderManifests(packageJson);
  for (const entry of await claudeSkillEntries({ root })) {
    outputs.set(`skills/${entry.name}/SKILL.md`, renderWrapper(entry));
  }
  outputs.set('skills/kit-root/SKILL.md', renderKitRoot());
  return outputs;
}

export async function validatePluginBuild({ root = packageRoot } = {}) {
  const failures = [];
  const expected = await expectedPluginFiles({ root });
  for (const [relativePath, content] of expected) {
    try {
      if (await fs.readFile(path.join(root, relativePath), 'utf8') !== content) failures.push(`Generated plugin file drift: ${relativePath}`);
    } catch {
      failures.push(`Generated plugin file missing: ${relativePath}`);
    }
  }
  for (const directory of generatedDirectories) {
    for (const relativePath of await listFiles(root, directory)) {
      if (!expected.has(relativePath)) failures.push(`Orphaned generated plugin file: ${relativePath}`);
    }
  }
  return { ok: failures.length === 0, failures, count: expected.size };
}

export async function writePluginBuild({ root = packageRoot } = {}) {
  const expected = await expectedPluginFiles({ root });
  for (const [relativePath, content] of expected) {
    const target = path.join(root, relativePath);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content, 'utf8');
  }
  return expected.size;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    console.log(`Wrote ${await writePluginBuild()} generated plugin files.`);
  } else {
    const result = await validatePluginBuild();
    if (!result.ok) {
      console.error('Plugin build validation failed (run node scripts/build-plugin.mjs --write):');
      for (const failure of result.failures) console.error(`- ${failure}`);
      process.exit(1);
    }
    console.log(`Plugin build is synchronized (${result.count} files).`);
  }
}

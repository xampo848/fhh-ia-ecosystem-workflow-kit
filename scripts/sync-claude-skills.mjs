#!/usr/bin/env node
// Exposes the kit's user-invocable workflow skills as native Claude Code
// skills (roadmap U-19c): Claude Code lists only their description and loads
// the body when the user types /<name>. Every wrapper sets
// disable-model-invocation, so Claude never starts a workflow on its own from
// the description: freeform requests still go through the level pre-filter and
// workflow-router, and a slash command counts as explicit skill invocation.
// Usage: node scripts/sync-claude-skills.mjs [--write]
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedMarker = 'Generated by scripts/sync-claude-skills.mjs. Do not edit.';
const templatePrefix = 'templates/runtime-adapters/claude';

export const claudeSkillKeys = [
  'workflow-router',
  'project-formation',
  'create-epic',
  'create-prd',
  'generate-pm-ticket',
  'solution-sketch',
  'implement-change',
  'implement-prd',
  'document-development',
  'pr-comments-resolution',
  'engineering-mentor'
];

function renderClaudeSkill(entry) {
  const description = String(entry.trigger).replace(/\s+/g, ' ').replace(/"/g, "'").trim();
  return `---
name: ${entry.name}
description: "${description}"
disable-model-invocation: true
---

<!-- ${generatedMarker} -->

Explicit invocation of the \`${entry.name}\` workflow skill.

Load \`${entry.path}\` and follow it. That file is the canonical procedure; this wrapper only makes it available as \`/${entry.name}\` in Claude Code.

It is never invoked automatically: freeform requests keep going through the level pre-filter and \`workflow-router\`.
`;
}

export async function expectedClaudeSkills({ root = packageRoot } = {}) {
  const registry = JSON.parse(await fs.readFile(path.join(root, '.agents/skills/registry.json'), 'utf8'));
  const entries = [...(registry.skills ?? []), ...(registry.pattern_skills ?? [])];
  const outputs = new Map();
  for (const key of claudeSkillKeys) {
    const entry = entries.find((item) => item.key === key);
    if (!entry) throw new Error(`Skill "${key}" is not in .agents/skills/registry.json.`);
    const content = renderClaudeSkill(entry);
    const relativePath = `.claude/skills/${entry.name}/SKILL.md`;
    outputs.set(relativePath, content);
    outputs.set(`${templatePrefix}/${relativePath}`, content);
  }
  return outputs;
}

export async function validateClaudeSkills({ root = packageRoot } = {}) {
  const failures = [];
  const expected = await expectedClaudeSkills({ root });
  for (const [relativePath, content] of expected) {
    try {
      if (await fs.readFile(path.join(root, relativePath), 'utf8') !== content) failures.push(`Generated Claude skill drift: ${relativePath}`);
    } catch {
      failures.push(`Generated Claude skill missing: ${relativePath}`);
    }
  }
  return { ok: failures.length === 0, failures, count: expected.size };
}

export async function writeClaudeSkills({ root = packageRoot } = {}) {
  const expected = await expectedClaudeSkills({ root });
  for (const [relativePath, content] of expected) {
    const target = path.join(root, relativePath);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content, 'utf8');
  }
  return expected.size;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    console.log(`Wrote ${await writeClaudeSkills()} generated Claude skill files.`);
  } else {
    const result = await validateClaudeSkills();
    if (!result.ok) {
      console.error('Claude skill validation failed (run node scripts/sync-claude-skills.mjs --write):');
      for (const failure of result.failures) console.error(`- ${failure}`);
      process.exit(1);
    }
    console.log(`Claude skills are synchronized (${result.count} files).`);
  }
}
